/** Deterministic = never calls a model. Model = single LLM call. Hybrid = deterministic
 *  path first, model only on fallback. Every task in this catalog is executed through a
 *  Pydantic AI task — there is no other task-execution mechanism. */
export type Impl = "Deterministic" | "Model" | "Hybrid";

export interface WorkflowDef {
  id:                  string;
  name:                string;
  category:            CategoryName;
  impl:                Impl;
  inputs:              string;
  outputs:             string;
  promptInstructions:  string;
  businessLogic:       string;
  configParameters:    string;
  escalateWhen:        string;
  typicalChain:        string;
}

